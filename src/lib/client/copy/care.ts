export const CARE_COPY: Record<Language, CareCopy> = { fr, ar };

/** Patient text of an approved action template; unknown templates are labelled, never guessed. */
export function templateText(templateId: string, lang: Language): string {
  const table = CARE_COPY[lang].template as Record<string, string>;
  return Object.hasOwn(table, templateId) ? table[templateId] : table.unknown;
}

export function questionLabel(labelKey: string, lang: Language): string {
  const table = CARE_COPY[lang].question as Record<string, string>;
  return Object.hasOwn(table, labelKey) ? table[labelKey] : table.unknown;
}

export function claimCodeLabel(code: string, lang: Language = "fr"): string {
  const table = CARE_COPY[lang].claimCode as Record<string, string>;
  return Object.hasOwn(table, code) ? table[code] : table.unknown;
}

/**
 * Display label of a medical fact. Onboarding answers are stored with the
 * registry code as label ("hypertension", "diabetes", "declared"); show the
 * FR/AR name for known codes and the fact kind for "declared". A label typed
 * by the patient is shown as written. Nothing is inferred beyond the code.
 */
export function factDisplayLabel(fact: Pick<MedicalFact, "kind" | "code" | "label">, lang: Language): string {
  const copy = CARE_COPY[lang];
  const label = fact.label.trim();
  const codes = copy.factCode as Record<string, string>;
  if (fact.code && label === fact.code && Object.hasOwn(codes, fact.code)) return codes[fact.code];
  if (label === "" || label === "declared") return copy.factKind[fact.kind];
  return label;
}
